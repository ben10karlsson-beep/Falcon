/* Turn the solver dumps in solver/work/ into js/solved.js, the compact data the site loads.
   Usage: node solver/export.js
   Per flop: BTN's mix after BB checks (check / bet 33% / bet 75%), the same split by hand type
   (Engine.classifyFlop buckets, with each bucket's share of BTN's range), and BB's answer to each size.
   Also writes js/solved-combos.js: BTN's mix for every single combo after BB checks (for the c-bet trainer). */
const fs = require("fs"), path = require("path");
const E = require("../js/engine.js");
const { btnRange, bbCallRange } = require("./make-config.js");
const flops = require("./flops.js");

const R = "AKQJT98765432";
function handKey(c) {
  let [a, s1, b, s2] = c; if (R.indexOf(a) > R.indexOf(b)) [a, s1, b, s2] = [b, s2, a, s1];
  return a === b ? a + b : a + b + (s1 === s2 ? "s" : "o");
}
const r3 = x => Math.round(x * 1000) / 1000;
const btn = btnRange(), bb = bbCallRange();

// Range-weighted action mix at a node, optionally split by hand bucket. Weight = the player's preflop frequency.
function mix(node, rng, board) {
  const s = node.strategy, n = s.actions.length;
  const all = Array(n).fill(0), by = E.BUCKETS.map(() => Array(n).fill(0)), bw = E.BUCKETS.map(() => 0);
  let w = 0;
  for (const [c, p] of Object.entries(s.strategy)) {
    const f = rng[handKey(c)] || 0; if (!f) continue;
    const b = board && E.classifyFlop([E.parseCard(c.slice(0, 2)), E.parseCard(c.slice(2))], board);
    w += f; if (board) bw[b] += f;
    p.forEach((x, i) => { all[i] += f * x; if (board) by[b][i] += f * x; });
  }
  return { actions: s.actions, all: all.map(x => x / w), by: by.map((v, b) => v.map(x => bw[b] ? x / bw[b] : 0)), share: bw.map(x => x / w) };
}
const pick = (m, acts, v) => acts.map(a => r3(v[m.actions.findIndex(x => a(x))] || 0));
const BTN_ACTS = [a => a === "CHECK", a => a.startsWith("BET 18"), a => a.startsWith("BET 41")];
const BB_ACTS = [a => a === "FOLD", a => a === "CALL", a => a.startsWith("RAISE")];

const out = [], combos = {};
// Per-combo mixes are stored in 2% steps as one character each: 0-9, A-Z, a-z map to 0..61 (only 0..50 used)
const ALPHA = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";
function comboString(node) {
  const s = node.strategy, iS = s.actions.findIndex(BTN_ACTS[1]), iB = s.actions.findIndex(BTN_ACTS[2]);
  return Object.entries(s.strategy).filter(([c]) => btn[handKey(c)]).map(([c, p]) => {
    const sm = Math.round(p[iS] * 50), bg = Math.min(50 - sm, Math.round(p[iB] * 50));
    return c + ALPHA[sm] + ALPHA[bg];
  }).join("");
}
for (const f of flops) {
  const file = path.join(__dirname, "work", f.board.replace(/,/g, "") + ".json");
  if (!fs.existsSync(file)) { console.error("missing", f.board); process.exit(1); }
  const res = JSON.parse(fs.readFileSync(file, "utf8")), ip = res.childrens.CHECK;
  const board = f.board.split(",").map(E.parseCard);
  const m = mix(ip, btn, board);
  const resp = key => {
    const r = mix(ip.childrens[Object.keys(ip.childrens).find(k => k.startsWith(key))], bb);
    // All raise sizes (check-raise and check-raise all-in) count as one "raise"
    const raise = r.actions.reduce((s, a, i) => s + (a.startsWith("RAISE") ? r.all[i] : 0), 0);
    return [r3(r.all[r.actions.indexOf("FOLD")]), r3(r.all[r.actions.indexOf("CALL")]), r3(raise)];
  };
  combos[f.board.replace(/,/g, "")] = comboString(ip);
  out.push({
    board: f.board.replace(/,/g, ""), family: f.family,
    btn: pick(m, BTN_ACTS, m.all),
    byHand: E.BUCKETS.map((_, b) => [r3(m.share[b]), ...pick(m, BTN_ACTS, m.by[b])]),
    vsSmall: resp("BET 18"), vsBig: resp("BET 41")
  });
}

const js = `/* Falcon solved flops: BTN opens 2.5bb, BB calls, 100bb. Generated by solver/export.js from TexasSolver runs
   using Falcon's own BTN opening and BB calling charts. Do not edit by hand.
   btn: BTN after BB checks [check, bet 33% pot, bet 75% pot]
   byHand: per Engine.BUCKETS hand type [share of BTN's range, check, bet 33%, bet 75%]
   vsSmall / vsBig: BB facing that bet [fold, call, raise] */
(function (root) {
  const SOLVED = ${JSON.stringify({ spot: "BTN vs BB", pot: 5.5, behind: 97.5, sizes: [0.33, 0.75], flops: out })
    .replace(/\{"board"/g, '\n  {"board"')};
  if (typeof module === "object" && module.exports) module.exports = SOLVED; else root.Solved = SOLVED;
})(this);
`;
fs.writeFileSync(path.join(__dirname, "../js/solved.js"), js);
const cjs = `/* Falcon solved flops, per combo: BTN's strategy for each hand after BB checks (BTN opens, BB calls, 100bb).
   Generated by solver/export.js from the same TexasSolver runs as js/solved.js. Do not edit by hand.
   Per flop, a string of 6-character entries: the combo (e.g. "AhKd"), then bet 33% and bet 75% as one character each
   in 2% steps: the character's index in "${ALPHA}" times 2%. Check is the rest. */
(function (root) {
  const COMBOS = ${JSON.stringify(combos).replace(/","/g, '",\n  "')};
  if (typeof module === "object" && module.exports) module.exports = COMBOS; else root.SolvedCombos = COMBOS;
})(this);
`;
fs.writeFileSync(path.join(__dirname, "../js/solved-combos.js"), cjs);
console.log(`wrote js/solved-combos.js: ${(cjs.length / 1024).toFixed(1)} KB`);
console.log(`wrote js/solved.js: ${out.length} flops, ${(js.length / 1024).toFixed(1)} KB`);
