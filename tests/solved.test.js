/* Run with: node tests/solved.test.js
   Sanity checks on js/solved.js (generated by solver/export.js from TexasSolver runs). */
const S = require("../js/solved.js");
const E = require("../js/engine.js");
const flops = require("../solver/flops.js");

let pass = 0, fail = 0;
function check(name, cond, info) {
  if (cond) pass++; else { fail++; console.log("FAIL:", name, info !== undefined ? info : ""); }
}
const sum = a => a.reduce((s, x) => s + x, 0);
const near1 = x => Math.abs(x - 1) < 0.01;

check("one entry per flop in solver/flops.js", S.flops.length === flops.length, S.flops.length);
for (const f of flops) check("solved " + f.board, S.flops.some(s => s.board === f.board.replace(/,/g, "")));
for (const f of S.flops) {
  const cards = E.parseCards(f.board.match(/../g).join(" "));
  check(f.board + " is three distinct cards", cards.length === 3 && new Set(cards).size === 3);
  check(f.board + " BTN mix sums to 1", near1(sum(f.btn)), sum(f.btn));
  check(f.board + " vs small sums to 1", near1(sum(f.vsSmall)), sum(f.vsSmall));
  check(f.board + " vs big sums to 1", near1(sum(f.vsBig)), sum(f.vsBig));
  check(f.board + " hand-type shares sum to 1", near1(sum(f.byHand.map(r => r[0]))));
  f.byHand.forEach((r, i) => { if (r[0] > 0) check(`${f.board} ${E.BUCKETS[i]} mix sums to 1`, near1(sum(r.slice(1))), sum(r.slice(1))); });
  // The by-hand split must add back up to the overall mix
  [0, 1, 2].forEach(a => check(`${f.board} action ${a} matches by-hand total`, Math.abs(sum(f.byHand.map(r => r[0] * r[a + 1])) - f.btn[a]) < 0.01));
  // BB folds more to the bigger bet
  check(f.board + " BB folds more to 75% than 33%", f.vsBig[0] > f.vsSmall[0]);
}
// Strong hands should bet more often than hands with nothing, on every flop where both exist
for (const f of S.flops) {
  const bet = r => r[2] + r[3];
  if (f.byHand[0][0] > 0.01 && f.byHand[4][0] > 0.01) check(f.board + " strong hands bet more than air", bet(f.byHand[0]) > bet(f.byHand[4]));
}

console.log(`${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
